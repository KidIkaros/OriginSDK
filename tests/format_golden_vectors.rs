#[test]
fn falcon512_keygen_and_sign_golden() {
    let (sk, pk) = falcon512::generate_keypair([0x42; 32]);
    assert_eq!(sha3_hex(&pk.0), F512_PK_SHA3, "pk wire format drifted");
    assert_eq!(
        sha3_hex(sk.as_bytes()),
        F512_SK_SHA3,
        "sk wire format drifted"
    );

    let sig = falcon512::sign_deterministic(b"golden", &sk, &[0xAA; 32]).unwrap();
    assert_eq!(sha3_hex(&sig.0), F512_SIG_SHA3, "sig format drifted");
    assert!(falcon512::verify(b"golden", &sig, &pk));
}

