#[test]
fn ed448_key_and_signature_golden() {
    let sk = ed448::SigningKey::from_bytes(&[0x11; 57]).unwrap();
    assert_eq!(
        hex::encode(sk.verifying_key().to_bytes()),
        ED448_PK,
        "pk derivation drifted"
    );
    let sig = sk.sign(b"golden");
    assert_eq!(hex::encode(sig.to_bytes()), ED448_SIG, "signature drifted");
    sk.verifying_key().verify(b"golden", &sig).unwrap();
}

