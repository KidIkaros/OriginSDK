//! Byte-exact golden vectors for SDK-owned persistent formats.
//!
//! Regression fixtures for formats flagged in `FORMAT_REGISTRY.md`:
//! Falcon-512/1024, Ed448, Ed41417, recovery phrase, Reed-Solomon.
//! (sntrup761 is covered by the official NIST KATs in
//! `tests/ntru_prime_kat.rs` — stronger than a self-generated golden.)
//!
//! Large artifacts (Falcon keys/signatures) are pinned by SHA3-256 digest —
//! any drift in wire format or algorithm changes the digest. Small artifacts
//! (Ed448/Ed41417 keys and signatures, phrase words, RS output) are pinned
//! byte-exact.

use origin_crypto_sdk::error_correction::ReedSolomonCodec;
use origin_crypto_sdk::pqc::{curve41417::ed41417, ed448, falcon1024, falcon512};
use origin_crypto_sdk::recovery::unicode_cipher::{encode_phrase, PhraseLength, UnicodeWordlist};
use sha3::{Digest, Sha3_256};

fn sha3_hex(data: &[u8]) -> String {
    let mut h = Sha3_256::new();
    h.update(data);
    hex::encode(h.finalize())
}

/// Regenerate the constants below if the format intentionally changes:
/// `cargo test --test format_golden_vectors print_vectors -- --ignored --nocapture`
#[test]
#[ignore]
fn print_vectors() {
    let (sk512, pk512) = falcon512::generate_keypair([0x42; 32]);
    let sig512 = falcon512::sign_deterministic(b"golden", &sk512, &[0xAA; 32]).unwrap();
    eprintln!("F512_PK={}", sha3_hex(&pk512.0));
    eprintln!("F512_SK={}", sha3_hex(sk512.as_bytes()));
    eprintln!("F512_SIG={}", sha3_hex(&sig512.0));

    let (pk1024, sk1024) = falcon1024::generate_keypair_from_seed(&[0x99; 32]).unwrap();
    let sig1024 = falcon1024::sign_deterministic(b"golden", &sk1024, &[0xBB; 32]).unwrap();
    eprintln!("F1024_PK={}", sha3_hex(pk1024.as_bytes()));
    eprintln!("F1024_SK={}", sha3_hex(sk1024.as_bytes()));
    eprintln!("F1024_SIG={}", sha3_hex(sig1024.as_bytes()));

    let ed_sk = ed448::SigningKey::from_bytes(&[0x11; 57]).unwrap();
    let ed_sig = ed_sk.sign(b"golden");
    eprintln!("ED448_PK={}", hex::encode(ed_sk.verifying_key().to_bytes()));
    eprintln!("ED448_SIG={}", hex::encode(ed_sig.to_bytes()));

    let c_sk = ed41417::SigningKey::from_bytes_mod_order([0x33; 52]);
    let c_sig = c_sk.sign(b"golden");
    eprintln!(
        "ED41417_PK={}",
        hex::encode(c_sk.verifying_key().as_bytes())
    );
    eprintln!("ED41417_SIG={}", hex::encode(c_sig.to_bytes()));

    let list = UnicodeWordlist::default();
    let p12 = encode_phrase(&[0x5Au8; 16], &list, PhraseLength::Words12).unwrap();
    let p24 = encode_phrase(&[0xA5u8; 32], &list, PhraseLength::Words24).unwrap();
    eprintln!("PHRASE12={}", p12.iter().collect::<String>());
    eprintln!("PHRASE24={}", p24.iter().collect::<String>());

    let rs = ReedSolomonCodec::new(4, 2);
    let enc = rs.encode(b"golden-rs-input!").unwrap();
    eprintln!("RS_ENC={}", hex::encode(&enc));
}

