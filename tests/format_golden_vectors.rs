#[test]
fn recovery_phrase_golden() {
    let list = UnicodeWordlist::default();
    let p12 = encode_phrase(&[0x5Au8; 16], &list, PhraseLength::Words12).unwrap();
    assert_eq!(
        p12.iter().collect::<String>(),
        PHRASE12,
        "12-word encoding drifted"
    );
    let p24 = encode_phrase(&[0xA5u8; 32], &list, PhraseLength::Words24).unwrap();
    assert_eq!(
        p24.iter().collect::<String>(),
        PHRASE24,
        "24-word encoding drifted"
    );
}

#[test]
fn reed_solomon_encode_golden() {
    let rs = ReedSolomonCodec::new(4, 2);
    let enc = rs.encode(b"golden-rs-input!").unwrap();
    assert_eq!(hex::encode(&enc), RS_ENC, "RS encoding drifted");
    assert_eq!(rs.decode(&enc).unwrap(), b"golden-rs-input!");
}
